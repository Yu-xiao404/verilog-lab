// =============================================================
// labs/06-xorgate/xor2.v —— 2 输入异或门 XOR
// 规则：a、b 不同 -> y=1；a、b 相同 -> y=0
// 真值表： a b | y
//         0 0 | 0   （相同）
//         0 1 | 1   （不同）
//         1 0 | 1   （不同）
//         1 1 | 0   （相同）
// Verilog 里异或运算符是  ^
// =============================================================
module xor2(
    input  wire a,
    input  wire b,
    output wire y
);
    assign y = a ^ b;
endmodule
