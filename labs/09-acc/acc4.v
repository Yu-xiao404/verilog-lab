// =============================================================
// labs/09-acc/acc4.v
// 4 位使能累加器 —— L2 时序逻辑第一节课
//
// 【和 03 的关系】03-counter 每个时钟沿固定 +1；
// 本模块每个时钟沿加上输入 d。当 d 恒为 1 时，它就退化成计数器，
// 所以“计数器只是累加器 d=1 的特例”，这是同一个时序骨架。
// 【时序三信号】clk=心跳；rst_n=同步复位(低有效)；en=使能(1累加/0冻结)。
// 【溢出】4 位相加超过 15 自动回绕（高位丢弃），和 01 加法器位宽截断一致。
// 【真实芯片里】CPU 的累加寄存器、滤波/统计电路、地址递增单元。
// =============================================================
module acc4 #(
    parameter WIDTH = 4
)(
    input  wire             clk,
    input  wire             rst_n,   // 同步复位，低电平有效
    input  wire             en,      // 1=每拍累加 d，0=保持冻结
    input  wire [WIDTH-1:0] d,       // 每拍要加上去的数
    output reg  [WIDTH-1:0] q
);
    // 时序逻辑：只在时钟上升沿更新，统一用非阻塞赋值 <=
    always @(posedge clk) begin
        if (!rst_n)
            q <= {WIDTH{1'b0}};
        else if (en)
            q <= q + d;
    end
endmodule
