// =============================================================
// labs/01-adder/adder4.v
// 4 位二进制加法器 —— 组合逻辑入门
//
// 【知识点】组合逻辑：没有时钟、没有记忆，输出完全由当前输入
// 决定，类似软件里的“纯函数”。
// 【真实芯片里的位置】CPU 的 ALU（算术逻辑单元）、地址计算、
// 乘法器内部，都是由大量加法单元堆叠而成的。
// =============================================================
module adder4 #(
    parameter WIDTH = 4              // 参数化位宽：例化时可改成 8/16/32
)(
    input  wire [WIDTH-1:0] a,       // 加数 A
    input  wire [WIDTH-1:0] b,       // 加数 B
    input  wire             cin,     // 来自低位的进位
    output wire [WIDTH-1:0] sum,     // 和
    output wire             cout     // 向高位的进位输出
);
    // 位拼接 {cout, sum} 组成 WIDTH+1 位：
    // 4 位 + 4 位 + 进位最大为 31，需要第 5 位存放溢出的进位
    assign {cout, sum} = a + b + cin ;
endmodule
